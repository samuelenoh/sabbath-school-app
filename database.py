"""Small DB-API adapter for the app's fixed SQL, SQLite locally and PostgreSQL hosted.

Postgres transactions take an advisory lock shared by all app instances. This
preserves SQLite's serialized mutation semantics; this app targets small churches.
"""
import re, sqlite3
from contextlib import contextmanager

LOCK_ID=1397968211
IDENTITY_TABLES={'users','records','audit','messages','rules'}

def is_postgres(target):
    return isinstance(target,str) and target.startswith(('postgres://','postgresql://'))

class PostgresCursor:
    def __init__(self,cursor,lastrowid=None):self.cursor=cursor;self.lastrowid=lastrowid
    def fetchone(self):return self.cursor.fetchone()
    def fetchall(self):return self.cursor.fetchall()
    def __iter__(self):return iter(self.cursor)

class PostgresConnection:
    def __init__(self,raw,driver):self.raw=raw;self.driver=driver;self.total_changes=0
    def execute(self,sql,parameters=()):
        # The application uses only fixed SQL; data always stay bound parameters.
        query=sql.strip().rstrip(';')
        if query.upper()=='BEGIN IMMEDIATE':
            cur=self.raw.execute('SELECT pg_advisory_xact_lock(%s)',(LOCK_ID,))
            return PostgresCursor(cur)
        if query.upper().startswith('PRAGMA '):return None
        if query.startswith('INSERT OR REPLACE INTO login_attempts'):
            query='INSERT INTO login_attempts VALUES(?,?,?) ON CONFLICT(key) DO UPDATE SET count=excluded.count,until=excluded.until'
        if query.startswith('INSERT OR IGNORE INTO '):
            query=query.replace('INSERT OR IGNORE INTO ','INSERT INTO ',1)+' ON CONFLICT DO NOTHING'
        match=re.match(r'INSERT INTO (\w+)',query,re.I)
        returning=bool(match and match.group(1).lower() in IDENTITY_TABLES)
        if returning:query+=' RETURNING id'
        parts=re.split(r"('(?:''|[^'])*')",query)
        query=''.join(part.replace('?','%s') if i%2==0 else part for i,part in enumerate(parts))
        try:
            cur=self.raw.execute(query,parameters or None)
        except self.driver.IntegrityError as error:
            raise sqlite3.IntegrityError('Database constraint violation.') from error
        if query.upper().startswith(('INSERT ','UPDATE ','DELETE ')):self.total_changes+=max(0,cur.rowcount)
        row=cur.fetchone() if returning else None
        return PostgresCursor(cur,row['id'] if row else None)
    def executescript(self,sql):
        sql=re.sub(r'\bid INTEGER PRIMARY KEY\b','id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY',sql)
        sql=re.sub(r'\bREAL\b','DOUBLE PRECISION',sql)
        for statement in sql.split(';'):
            if statement.strip():self.execute(statement)
    def commit(self):self.raw.commit()

@contextmanager
def connection(target):
    if is_postgres(target):
        import psycopg
        from psycopg.rows import dict_row
        raw=psycopg.connect(target,row_factory=dict_row,connect_timeout=15)
        try:
            with raw:
                c=PostgresConnection(raw,psycopg)
                c.execute('BEGIN IMMEDIATE')
                yield c
        finally:raw.close()
    else:
        raw=sqlite3.connect(target,timeout=15);raw.row_factory=sqlite3.Row
        raw.execute('PRAGMA foreign_keys=ON')
        try:
            with raw:yield raw
        finally:raw.close()
